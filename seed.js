export async function seedUsers() {
  const client = new MongoClient(uri);
  try {
    await client.connect();
    console.log("Connected to MongoDB successfully for seeding.");
    const db = client.db(dbName);
    const usersCol = db.collection('user');

    // Upsert demo users by email so re-running seed is idempotent
    let inserted = 0;
    let updated = 0;

    for (const user of demoUsers) {
      const res = await usersCol.updateOne(
        { email: user.email },
        { $set: user },
        { upsert: true }
      );
      if (res.upsertedCount > 0) inserted++;
      else if (res.modifiedCount > 0) updated++;
    }

    const total = await usersCol.countDocuments();
    console.log(`✅ Seeding complete! Inserted: ${inserted}, Updated: ${updated}. Total users in database: ${total}`);
  } catch (err) {
    console.error("❌ Seeding Error:", err);
  } finally {
    await client.close();
  }
}

// Execute if run directly from CLI
if (process.argv[1]?.endsWith('seed.js')) {
  seedUsers();
}
